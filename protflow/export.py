"""
Thin exporter from ProtFlow manifests to Nextflow processes and Snakemake rules.
Translates manifests into native pipeline specifications without bloat.
"""

from __future__ import annotations
from datetime import datetime
from pathlib import Path
from typing import List, Union
from protflow.manifest import Manifest


def manifest_to_snakemake_rule(m: Manifest) -> str:
    """Translates a ProtFlow Manifest into a Snakemake rule."""
    inputs_lines = [f"        {k}=\"data/{k}/{{sample}}\"" for k in m.inputs]
    outputs_lines = [f"        {k}=\"results/{m.name}/{k}/{{sample}}\"" for k in m.outputs]

    rule_parts = [
        f"rule {m.name}:",
        f"    # ProtFlow auto-generated rule for {m.name} v{m.version}",
        "    input:",
        "\n".join(inputs_lines) if inputs_lines else "        # no inputs",
        "    output:",
        "\n".join(outputs_lines) if outputs_lines else "        # no outputs",
    ]

    if m.execution.type == "container" and m.execution.image:
        rule_parts.append(f'    container: "{m.execution.image}"')

    if m.execution.type in ("local", "container") and m.execution.command:
        rule_parts.extend([
            "    shell:",
            f'        "{m.execution.command}"'
        ])
    elif m.execution.type == "http":
        rule_parts.extend([
            "    run:",
            f'        # Remote HTTP service: {m.execution.url}',
            f'        import protflow.runner; from protflow.manifest import Manifest',
            f'        # Dispatches via ProtFlow HTTP runner adapter: {m.adapter}'
        ])

    return "\n".join(rule_parts)


def manifest_to_nextflow_process(m: Manifest) -> str:
    """Translates a ProtFlow Manifest into a Nextflow process."""
    lines = [
        f"process {m.name.upper()} {{",
        f"    // ProtFlow auto-generated process for {m.name} v{m.version}",
        f"    tag \"${{sample}}\""
    ]

    if m.execution.type == "container" and m.execution.image:
        lines.append(f"    container '{m.execution.image}'")

    lines.append("\n    input:")
    for in_name in m.inputs:
        lines.append(f"    tuple val(sample), path({in_name})")

    lines.append("\n    output:")
    for out_name in m.outputs:
        lines.append(f"    tuple val(sample), path(\"{out_name}*\")")

    lines.append("\n    script:")
    if m.execution.type in ("local", "container") and m.execution.command:
        lines.append(f"    \"\"\"\n    {m.execution.command}\n    \"\"\"")
    else:
        in_args = " ".join(f"--input {k}=${{{k}}}" for k in m.inputs)
        in_suffix = f" {in_args}" if in_args else ""
        lines.append(f"    \"\"\"\n    # HTTP API / Custom Adapter: {m.adapter}\n    python -m protflow.runner --manifest {m.name}.yaml --sample ${{sample}}{in_suffix}\n    \"\"\"")

    lines.append("}")

    return "\n".join(lines)


def export_pipeline_to_snakemake(manifests: List[Manifest]) -> str:
    """Exports a list of manifests as a complete Snakefile."""
    header = (
        "# Snakefile generated by ProtFlow\n"
        "# Automatic execution mapping for zero-friction tool nodes\n\n"
    )
    rules = [manifest_to_snakemake_rule(m) for m in manifests]
    return header + "\n\n".join(rules) + "\n"


def export_pipeline_to_nextflow(manifests: List[Manifest]) -> str:
    """Exports a list of manifests as a complete main.nf."""
    header = (
        "// main.nf generated by ProtFlow\n"
        "nextflow.enable.dsl=2\n\n"
    )
    processes = [manifest_to_nextflow_process(m) for m in manifests]
    return header + "\n\n".join(processes) + "\n"


def export_sequence_to_genbank(cds_seq, out_path: Union[str, Path], organism: str = "Synthetic construct") -> Path:
    """Exports an optimized nucleotide sequence to flat GenBank format."""
    p = Path(out_path)
    p.parent.mkdir(parents=True, exist_ok=True)
    nt_len = len(cds_seq.sequence)
    seq = cds_seq.sequence.lower()

    origin_lines = []
    for i in range(0, nt_len, 60):
        chunk = seq[i:i+60]
        spaced = " ".join([chunk[j:j+10] for j in range(0, len(chunk), 10)])
        origin_lines.append(f"{i+1:9d} {spaced}")
    origin_block = "\n".join(origin_lines)

    today_str = datetime.now().strftime("%d-%b-%Y").upper()
    content = f"""LOCUS       {cds_seq.protein_id[:16]:<16} {nt_len} bp    DNA     linear   SYN {today_str}
DEFINITION  {cds_seq.description or cds_seq.protein_id}.
ACCESSION   {cds_seq.protein_id}
VERSION     {cds_seq.protein_id}.1
SOURCE      {organism}
  ORGANISM  {organism}
FEATURES             Location/Qualifiers
     source          1..{nt_len}
                     /organism="{organism}"
                     /mol_type="other DNA"
     CDS             1..{nt_len}
                     /gene="{cds_seq.protein_id}"
                     /codon_start=1
ORIGIN      
{origin_block}
//
"""
    p.write_text(content.strip() + "\n", encoding="utf-8")
    return p


def export_construct_package(cds_seq, codon_table, out_dir: Union[str, Path]) -> dict:
    """Exports multi-format construct package (.fasta, .gbk, .csv report, .parquet)."""
    d = Path(out_dir)
    d.mkdir(parents=True, exist_ok=True)
    pid = cds_seq.protein_id

    fasta_p = cds_seq.save_fasta(d / f"{pid}.fasta")
    gbk_p = export_sequence_to_genbank(cds_seq, d / f"{pid}.gbk")
    csv_p = d / f"{pid}_codon_report.csv"
    codon_table.df.to_csv(csv_p, index=False)
    parquet_p = codon_table.save_parquet(d / f"{pid}_codon_report.parquet")

    return {
        "fasta": fasta_p,
        "genbank": gbk_p,
        "csv": csv_p,
        "parquet": parquet_p
    }

