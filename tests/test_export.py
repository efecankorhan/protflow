"""
Tests for Snakemake and Nextflow export layer.
"""

from protflow.manifest import Manifest
from protflow.export import (
    manifest_to_snakemake_rule,
    manifest_to_nextflow_process,
    export_pipeline_to_snakemake,
    export_pipeline_to_nextflow
)


def test_snakemake_export():
    manifest = Manifest.from_dict({
        "name": "p2rank",
        "version": "2.4.1",
        "inputs": {"structure": "Structure"},
        "outputs": {"pockets": "Pocket"},
        "execution": {
            "type": "container",
            "image": "czbiohub/p2rank:2.4.1",
            "command": "p2rank predict -f {input.structure} -o {output_dir}"
        },
        "adapter": "protflow.adapters.parsers:parse_dummy_pocket_finder"
    })

    rule_str = manifest_to_snakemake_rule(manifest)
    assert "rule p2rank:" in rule_str
    assert "container: \"czbiohub/p2rank:2.4.1\"" in rule_str
    assert "p2rank predict" in rule_str

    snakefile = export_pipeline_to_snakemake([manifest])
    assert "# Snakefile generated by ProtFlow" in snakefile
    assert "rule p2rank:" in snakefile


def test_nextflow_export():
    manifest = Manifest.from_dict({
        "name": "p2rank",
        "version": "2.4.1",
        "inputs": {"structure": "Structure"},
        "outputs": {"pockets": "Pocket"},
        "execution": {
            "type": "container",
            "image": "czbiohub/p2rank:2.4.1",
            "command": "p2rank predict -f $structure"
        },
        "adapter": "protflow.adapters.parsers:parse_dummy_pocket_finder"
    })

    proc_str = manifest_to_nextflow_process(manifest)
    assert "process P2RANK {" in proc_str
    assert "container 'czbiohub/p2rank:2.4.1'" in proc_str
    assert "p2rank predict" in proc_str

    nf_file = export_pipeline_to_nextflow([manifest])
    assert "nextflow.enable.dsl=2" in nf_file
    assert "process P2RANK {" in nf_file
